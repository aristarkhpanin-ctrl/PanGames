/**
 * Шаблоны дневника острова (§8 ТЗ) — данные, не код.
 *
 * Дневник — то, ради чего игра открывается. Голос принадлежит жителю, а не системе:
 * «Ким подумывает, что тут кое-чего не хватает» — а не «Внимание: нехватка воды в секторе E».
 * Проблемы попадают сюда шёпотом: наблюдением, без призыва что-то делать (устав, п. 8).
 *
 * Разнообразие набирается комбинаторикой — главная фраза × время суток × добавка, — а не
 * длиной списка. Запись собирается из двух самостоятельных предложений: склеенные куски
 * одного предложения неминуемо разъезжаются в падежах.
 *
 * ## Три правила, которым подчинены все строки
 *
 * Русские слова согласуются, а имена жителей и названия зданий в игре — данные без пометок
 * о роде и падеже. Поэтому:
 *
 * 1. `{name}` и `{other}` всегда подлежащие, в именительном падеже. Никаких предлогов перед
 *    ними: «у Сева» — уже ошибка.
 * 2. Глаголы про людей — только настоящего времени. «Мира переехал» — ошибка, а рода
 *    у жителя нет и не будет (§5 ТЗ: житель — человек, а не роль).
 * 3. `{what}` стоит только после двоеточия или тире, то есть тоже в именительном.
 *    «Достроили лесопилка» и «шалаш готова» — ошибки из этой же семьи.
 *
 * Все три проверяются тестом по самим шаблонам, а не по готовым записям: так ошибка
 * находится в момент написания строки, а не через месяц у игрока.
 */

