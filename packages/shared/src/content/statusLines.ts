import type { AgentState } from '../types';

/**
 * Что житель делает — человеческим языком (§8 ТЗ).
 *
 * Данные, а не строки в компонентах: карточка жителя должна говорить «Сидит на своём камне,
 * смотрит на воду», а не «состояние: admire». Термины автомата игроку показывать нельзя.
 */

/** Варианты выбираются по сиду жителя — один и тот же человек говорит о себе одинаково. */
export const STATUS_LINES: Readonly<Record<AgentState, readonly string[]>> = {
  idle: ['Стоит и думает о своём', 'Осматривается', 'Никуда не спешит'],
  walk: ['Идёт через остров', 'Шагает по своим делам', 'Направляется куда-то'],
  work: ['Занимается делом', 'Работает не торопясь', 'Разбирается с делами'],
  eat: ['Обедает', 'Ест и смотрит по сторонам', 'Перекусывает'],
  sleep: ['Спит', 'Спит, укрывшись', 'Видит сны'],
  socialize: ['Разговаривает', 'Слушает и кивает', 'Болтает о пустяках'],
  wander: ['Бродит без цели', 'Гуляет', 'Изучает остров'],
  admire: ['Сидит и смотрит на воду', 'Любуется', 'Смотрит вдаль'],
  build: ['Строит', 'Носит доски', 'Ровняет стену'],
  haul: ['Несёт припасы', 'Таскает мешки', 'Переносит вещи'],
  celebrate: ['Празднует', 'Смеётся у огня', 'Танцует'],
};

export function statusLine(state: AgentState, seed: number): string {
  const lines = STATUS_LINES[state];
  return lines[Math.abs(seed) % lines.length] ?? lines[0] ?? 'Живёт';
}
