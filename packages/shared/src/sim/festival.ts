import type { ResourceId } from '../types';
import { TICKS_PER_HOUR } from './time';

/**
 * Праздник (§7 ТЗ).
 *
 * Жители сходятся к общему очагу, весь остров переходит в состояние `celebrate`, общение
 * и красота идут всплеском, а в дневнике появляется тёплая запись. Работа в этот вечер
 * стоит — и это не потеря, а смысл происходящего.
 *
 * Праздник ничего не открывает и никуда не ведёт. Наград за серию праздников нет.
 */

/** Сколько длится праздник: вечер, а не сутки. */
export const FESTIVAL_TICKS = 4 * TICKS_PER_HOUR;

/** Чего стоит праздник. Еда и немного тепла — денег в этой игре нет. */
export const FESTIVAL_COST: Partial<Record<ResourceId, number>> = { meal: 4, fruit: 6 };

/** Сколько вдохновения приносит праздник. Вдохновение — валюта уюта (§4 ТЗ). */
export const FESTIVAL_INSPIRATION = 12;

/** Что даёт красота: обустроенный остров сам собой рождает вдохновение. */
export const INSPIRATION_PER_EVENT = 3;
